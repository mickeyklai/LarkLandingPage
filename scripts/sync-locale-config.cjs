#!/usr/bin/env node
/**
 * Reads i18n/locales.json and regenerates:
 *   - netlify.toml locale redirect block (between markers)
 *   - i18n/locale-detect.js (early lang attribute from URL path)
 *
 * Run after adding a locale: node scripts/sync-locale-config.cjs
 */
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const localesPath = path.join(root, 'i18n', 'locales.json');
const netlifyPath = path.join(root, 'netlify.toml');
const detectPath = path.join(root, 'i18n', 'locale-detect.js');

const START = '# LOCALE_REDIRECTS_START';
const END = '# LOCALE_REDIRECTS_END';

const cfg = JSON.parse(fs.readFileSync(localesPath, 'utf8'));
const defaultLocale = cfg.default || 'en';
const codes = Object.keys(cfg.locales || {}).filter(function (code) {
  return code !== defaultLocale;
});

function rewriteRules(code, target) {
  return [
    '[[redirects]]',
    '  from = "/' + code + '"',
    '  to = "' + target + '"',
    '  status = 200',
    '',
    '[[redirects]]',
    '  from = "/' + code + '/"',
    '  to = "' + target + '"',
    '  status = 200',
  ].join('\n');
}

const lines = [
  START,
  '# Generated by scripts/sync-locale-config.cjs — edit i18n/locales.json instead',
  '',
];

codes.forEach(function (code) {
  lines.push(rewriteRules(code, '/index.html'));
  lines.push('');
  lines.push(rewriteRules(code, '/blog/index.html').replace(/\/index\.html/g, '/blog/index.html').replace('from = "/' + code + '"', 'from = "/' + code + '/blog"'));
  // blog index — fix the above is wrong, write explicitly
});

// Clear and rebuild properly
const redirectBlocks = [START, '# Generated by scripts/sync-locale-config.cjs — edit i18n/locales.json instead', ''];

codes.forEach(function (code) {
  redirectBlocks.push(rewriteRules(code, '/index.html'));
  redirectBlocks.push('');

  var meta = cfg.locales[code] || {};
  var home = '/' + code + '/';

  if (meta.blog !== false) {
    redirectBlocks.push([
      '[[redirects]]',
      '  from = "/' + code + '/blog"',
      '  to = "/blog/index.html"',
      '  status = 200',
      '',
      '[[redirects]]',
      '  from = "/' + code + '/blog/"',
      '  to = "/blog/index.html"',
      '  status = 200',
    ].join('\n'));
    redirectBlocks.push('');
    redirectBlocks.push([
      '[[redirects]]',
      '  from = "/' + code + '/blog/*"',
      '  to = "/blog/post.html"',
      '  status = 200',
    ].join('\n'));
    redirectBlocks.push('');
  } else {
    redirectBlocks.push([
      '[[redirects]]',
      '  from = "/' + code + '/blog"',
      '  to = "' + home + '"',
      '  status = 302',
      '',
      '[[redirects]]',
      '  from = "/' + code + '/blog/"',
      '  to = "' + home + '"',
      '  status = 302',
      '',
      '[[redirects]]',
      '  from = "/' + code + '/blog/*"',
      '  to = "' + home + '"',
      '  status = 302',
    ].join('\n'));
    redirectBlocks.push('');
  }

  redirectBlocks.push([
    '[[redirects]]',
    '  from = "/' + code + '/privacy-policy.html"',
    '  to = "/privacy-policy.html"',
    '  status = 200',
  ].join('\n'));
  redirectBlocks.push('');
});

redirectBlocks.push(END);

const generated = redirectBlocks.join('\n');

let netlify = fs.readFileSync(netlifyPath, 'utf8');
if (!netlify.includes(START) || !netlify.includes(END)) {
  console.error('sync-locale-config: markers missing in netlify.toml');
  process.exit(1);
}

netlify = netlify.replace(new RegExp(START + '[\\s\\S]*?' + END), generated);
fs.writeFileSync(netlifyPath, netlify, 'utf8');

const pathRe = codes.length ? '^\\/(' + codes.join('|') + ')(\\/|$)' : '^$';
const detectJs =
  '/* Generated by scripts/sync-locale-config.cjs — do not edit by hand */\n' +
  '(function(){var m=location.pathname.match(/' +
  pathRe +
  '/);if(m){document.documentElement.lang=m[1];var rtl=' +
  JSON.stringify(
    codes.reduce(function (acc, code) {
      if (cfg.locales[code] && cfg.locales[code].rtl) acc[code] = true;
      return acc;
    }, {}),
  ) +
  ';if(rtl[m[1]])document.documentElement.dir="rtl";' +
  'if(m[1]==="he"){var hd=document.head||document.documentElement;' +
  'var pf=document.createElement("link");pf.rel="preconnect";pf.href="https://fonts.gstatic.com";pf.crossOrigin="";hd.appendChild(pf);' +
  'var gf=document.createElement("link");gf.rel="stylesheet";gf.href="https://fonts.googleapis.com/css2?family=Heebo:wght@300;400;500;600;700&display=swap";hd.appendChild(gf);' +
  'var hc=document.createElement("link");hc.rel="stylesheet";hc.href="/css/he.css";hd.appendChild(hc);}' +
  '}})();\n';

fs.writeFileSync(detectPath, detectJs, 'utf8');

console.log('sync-locale-config: updated netlify.toml and i18n/locale-detect.js (' + codes.length + ' locale prefixes)');
